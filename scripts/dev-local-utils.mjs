export function collectStaleLocalEnvIssues({ apiVars, adminVars, storefrontVars }) {
  const files = [
    { name: "apps/api/.dev.vars", vars: apiVars },
    { name: "apps/admin-v2/.dev.vars", vars: adminVars },
    { name: "apps/storefront/.dev.vars", vars: storefrontVars },
  ].filter((file) => file.vars);

  const issues = [];
  for (const file of files) {
    const stale = RETIRED_LOCAL_ENV_KEYS.filter((key) => key in file.vars);
    if (stale.length > 0) {
      issues.push(`${file.name} still defines retired keys: ${stale.join(", ")}`);
    }
  }
  return issues;
}

export function assertPassword(password) {
  if (typeof password !== "string") {
    throw new Error("Local admin password must be provided as a string.");
  }
  if (password.length < 12) {
    throw new Error("Local admin password must be at least 12 characters.");
  }
}

export function resolveLocalStatePath(root, value) {
  if (!value) return resolve(root, ".wrangler", "state");
  return isAbsolute(value) ? value : resolve(root, value);
}

/** SCALIUS_SECRET must be at least this long (packages/shared/src/runtime-secrets.ts). */
export const MASTER_SECRET_MIN_LENGTH = 32;
/** CREDENTIAL_ENCRYPTION_KEY is an AES-256-GCM raw key: base64 of exactly 32 bytes. */
export const CREDENTIAL_ENCRYPTION_KEY_BYTES = 32;

/** Master secret: 48 random bytes, base64 (64 chars), same as `openssl rand -base64 48`. */
export function generateMasterSecret() {
  return crypto.randomBytes(48).toString("base64");
}

/** AES-256 key: 32 random bytes, base64 (44 chars), same as `openssl rand -base64 32`. */
export function generateCredentialEncryptionKey() {
  return crypto.randomBytes(CREDENTIAL_ENCRYPTION_KEY_BYTES).toString("base64");
}

export function isUsableMasterSecret(value) {
  return isUsableSecret(value) && value.trim().length >= MASTER_SECRET_MIN_LENGTH;
}

export function isUsableCredentialEncryptionKey(value) {
  if (!isUsableSecret(value)) return false;
  const trimmed = value.trim();
  if (!/^[A-Za-z0-9+/]+={0,2}$/.test(trimmed)) return false;
  const bytes = Buffer.from(trimmed, "base64");
  return bytes.length === CREDENTIAL_ENCRYPTION_KEY_BYTES
    && bytes.toString("base64") === trimmed;
}

export function parseEnvFileContent(content) {
  const values = {};
  for (const rawLine of content.split(/\r?\n/)) {
    let line = rawLine.trim();
    if (!line || line.startsWith("#")) continue;
    if (line.startsWith("export ")) line = line.slice("export ".length).trim();

    const equalsIndex = line.indexOf("=");
    if (equalsIndex <= 0) continue;

    const key = line.slice(0, equalsIndex).trim();
    const rawValue = line.slice(equalsIndex + 1).trim();
    values[key] = normalizeEnvValue(rawValue);
  }
  return values;
}

export function readEnvVarsIfExists(filePath) {
  if (!filePath || !existsSync(filePath)) return null;
  return parseEnvFileContent(readFileSync(filePath, "utf8"));
}

/**
 * Chooses the two installed local secrets, reusing usable values from the
 * environment or existing .dev.vars files (API first, then admin, then
 * storefront) and generating fresh ones only when nothing usable exists.
 */
export function resolveSharedLocalSecrets({
  forceRegenerate = false,
  apiVars = null,
  adminVars = null,
  storefrontVars = null,
  env = process.env,
} = {}) {
  const existingApi = forceRegenerate ? null : apiVars;
  const existingAdmin = forceRegenerate ? null : adminVars;
  const existingStorefront = forceRegenerate ? null : storefrontVars;

  return {
    scaliusSecret: firstMatchingValue(
      isUsableMasterSecret,
      [
        env.SCALIUS_SECRET,
        existingApi?.SCALIUS_SECRET,
        existingAdmin?.SCALIUS_SECRET,
        existingStorefront?.SCALIUS_SECRET,
      ],
      generateMasterSecret,
    ),
    credentialEncryptionKey: firstMatchingValue(
      isUsableCredentialEncryptionKey,
      [
        env.CREDENTIAL_ENCRYPTION_KEY,
        existingApi?.CREDENTIAL_ENCRYPTION_KEY,
        existingAdmin?.CREDENTIAL_ENCRYPTION_KEY,
      ],
      generateCredentialEncryptionKey,
    ),
  };
}

/** Which .dev.vars file must carry each installed secret, and how it is validated. */
export const LOCAL_SHARED_SECRETS = Object.freeze([
  Object.freeze({
    key: "SCALIUS_SECRET",
    files: Object.freeze(["apps/api/.dev.vars", "apps/admin-v2/.dev.vars", "apps/storefront/.dev.vars"]),
    isValid: isUsableMasterSecret,
    invalidReason: `must be at least ${MASTER_SECRET_MIN_LENGTH} characters`,
  }),
  Object.freeze({
    key: "CREDENTIAL_ENCRYPTION_KEY",
    files: Object.freeze(["apps/api/.dev.vars", "apps/admin-v2/.dev.vars"]),
    isValid: isUsableCredentialEncryptionKey,
    invalidReason: `must be base64 of exactly ${CREDENTIAL_ENCRYPTION_KEY_BYTES} bytes`,
  }),
]);

export function collectLocalSecretSyncIssues({ apiVars, adminVars, storefrontVars }) {
  const files = [
    { name: "apps/api/.dev.vars", vars: apiVars },
    { name: "apps/admin-v2/.dev.vars", vars: adminVars },
    { name: "apps/storefront/.dev.vars", vars: storefrontVars },
  ].filter((file) => file.vars);

  const issues = [];
  for (const secret of LOCAL_SHARED_SECRETS) {
    const relevantFiles = files.filter((file) => secret.files.includes(file.name));
    const missing = relevantFiles
      .filter((file) => !isUsableSecret(file.vars[secret.key]))
      .map((file) => file.name);
    if (missing.length > 0) {
      issues.push(`${secret.key} is missing from ${missing.join(", ")}`);
    }

    const invalid = relevantFiles
      .filter((file) => isUsableSecret(file.vars[secret.key]) && !secret.isValid(file.vars[secret.key]))
      .map((file) => file.name);
    if (invalid.length > 0) {
      issues.push(`${secret.key} ${secret.invalidReason} in ${invalid.join(", ")}`);
    }

    const valueOwners = new Map();
    for (const file of relevantFiles) {
      const value = file.vars[secret.key];
      if (!isUsableSecret(value)) continue;
      const owners = valueOwners.get(value.trim()) ?? [];
      owners.push(file.name);
      valueOwners.set(value.trim(), owners);
    }
    if (valueOwners.size > 1) {
      issues.push(`${secret.key} differs between local .dev.vars files`);
    }
  }
  return issues;
}

export function assertLocalSecretSync(envFiles) {
  const issues = collectLocalSecretSyncIssues(envFiles);
  if (issues.length === 0) return;

  throw new Error(
    [
      "Local .dev.vars shared secrets are out of sync.",
      ...issues.map((issue) => `- ${issue}`),
      "",
      "Run pnpm dev:setup --force --env-only to regenerate local env files without touching the database, or manually align the shared values.",
    ].join("\n"),
  );
}

function normalizeEnvValue(rawValue) {
  if (!rawValue) return "";
  const quote = rawValue[0];
  if ((quote === "\"" || quote === "'") && rawValue.at(-1) === quote) {
    return rawValue.slice(1, -1);
  }
  return rawValue.replace(/\s+#.*$/, "").trim();
}

function findCommandOnPath(command, pathValue) {
  if (!pathValue) return null;
  for (const dir of pathValue.split(delimiter)) {
    if (!dir) continue;
    const candidate = join(dir, command);
    if (isUsableFile(candidate)) return candidate;
  }
  return null;
}

function getHomePnpmCandidates(homeDir) {
  if (!homeDir) return [];

  const candidates = [
    join(homeDir, ".cache", "codex-runtimes", "codex-primary-runtime", "dependencies", "bin", "pnpm"),
    join(homeDir, "Library", "pnpm", "pnpm"),
  ];

  const nvmNodeVersionsDir = join(homeDir, ".nvm", "versions", "node");
  try {
    for (const version of readdirSync(nvmNodeVersionsDir)) {
      candidates.push(
        join(nvmNodeVersionsDir, version, "lib", "node_modules", "corepack", "shims", "pnpm"),
      );
    }
  } catch {
    // No nvm installation; the PATH/current-node candidates above are enough.
  }

  return candidates;
}

function isUsableFile(path) {
  return typeof path === "string" && path.length > 0 && existsSync(path);
}

function getSiblingPnpmExecutable(candidate) {
  const siblingPnpm = join(dirname(candidate), "pnpm");
  return isUsableFile(siblingPnpm) ? siblingPnpm : null;
}

function isNamedPnpmExecutable(candidate) {
  return isUsableFile(candidate) && basename(candidate) === "pnpm";
}

function firstMatchingValue(isValid, candidates, generate) {
  for (const candidate of candidates) {
    if (isValid(candidate)) return candidate.trim();
  }
  return generate();
}

function isUsableSecret(value) {
  return typeof value === "string" && !PLACEHOLDER_VALUES.has(value.trim());
}

function isLocalHostname(hostname) {
  const normalized = normalizeHostname(hostname);
  return normalized === "localhost" || normalized === "127.0.0.1" || normalized === "::1";
}

function normalizeHostname(hostname) {
  return hostname.toLowerCase().replace(/^\[/, "").replace(/\]$/, "");
}
