import crypto from "crypto";
import { existsSync, readFileSync, readdirSync } from "fs";
import { basename, delimiter, dirname, isAbsolute, join, resolve } from "path";

const PLACEHOLDER_VALUES = new Set(["", "<auto-generated>", "\"<auto-generated>\"", "'<auto-generated>'"]);

export function parseOptions(rawArgs) {
  const parsed = {};
  for (let i = 0; i < rawArgs.length; i++) {
    const arg = rawArgs[i];
    if (!arg.startsWith("--")) continue;
    const withoutPrefix = arg.slice(2);
    const equalsIndex = withoutPrefix.indexOf("=");
    if (equalsIndex >= 0) {
      parsed[withoutPrefix.slice(0, equalsIndex)] = withoutPrefix.slice(equalsIndex + 1);
      continue;
    }

    const next = rawArgs[i + 1];
    if (next && !next.startsWith("--")) {
      parsed[withoutPrefix] = next;
      i++;
    } else {
      parsed[withoutPrefix] = true;
    }
  }
  return parsed;
}

export function assertStringOptions(options, optionNames) {
  for (const name of optionNames) {
    if (options[name] === true) {
      throw new Error(`Option --${name} requires a value.`);
    }
  }
}

export function getArgValue(args, name) {
  const inline = args.find((arg) => arg.startsWith(`${name}=`));
  if (inline) return inline.slice(name.length + 1);
  const index = args.indexOf(name);
  if (index >= 0) {
    const value = args[index + 1];
    if (!value || value.startsWith("--")) {
      throw new Error(`Option ${name} requires a value.`);
    }
    return value;
  }
  return undefined;
}

export function shellQuote(value) {
  return `'${String(value).replace(/'/g, `'\\''`)}'`;
}

export function resolvePnpmExecutable({
  env = process.env,
  nodeExecPath = process.execPath,
} = {}) {
  const explicit = env.SCALIUS_PNPM_BIN || env.SCALIUS_PNPM_COMMAND;
  if (explicit && isNamedPnpmExecutable(explicit)) return explicit;
  if (explicit && isUsableFile(explicit)) {
    const sibling = getSiblingPnpmExecutable(explicit);
    if (sibling) return sibling;
  }
  if (explicit && !isUsableFile(explicit)) return explicit;

  const pathMatch = findCommandOnPath("pnpm", env.PATH);
  if (pathMatch) return pathMatch;

  if (isUsableFile(env.npm_execpath) && /pnpm|corepack/.test(env.npm_execpath)) {
    const sibling = getSiblingPnpmExecutable(env.npm_execpath);
    if (sibling) return sibling;
  }

  const nodePrefix = nodeExecPath ? dirname(dirname(nodeExecPath)) : null;
  const corepackFromNode = nodePrefix
    ? join(nodePrefix, "lib", "node_modules", "corepack", "shims", "pnpm")
    : null;
  if (isUsableFile(corepackFromNode)) return corepackFromNode;

  for (const candidate of getHomePnpmCandidates(env.HOME)) {
    if (isUsableFile(candidate)) return candidate;
  }

  return explicit && isUsableFile(explicit)
    ? explicit
    : isUsableFile(env.npm_execpath)
      ? env.npm_execpath
      : "pnpm";
}

export function pnpmShellCommand(options) {
  return shellQuote(resolvePnpmExecutable(options));
}

export function trimTrailingSlash(value) {
  return value.replace(/\/+$/, "");
}

export function assertLocalUrl(value) {
  const url = new URL(value);
  if (!isLocalHostname(url.hostname)) {
    throw new Error(`Refusing to run against non-local API URL: ${value}`);
  }
}

const SCALIUS_PRODUCTION_HOSTNAMES = new Set([
  "api.scalius.com",
  "dashboard.scalius.com",
  "storefront.scalius.com",
  "scalius.com",
  "www.scalius.com",
]);

export function classifyMutationTarget(value) {
  const url = new URL(value);
  const hostname = normalizeHostname(url.hostname);
  return {
    origin: url.origin,
    hostname,
    isLocal: isLocalHostname(hostname),
    isKnownProduction: SCALIUS_PRODUCTION_HOSTNAMES.has(hostname),
  };
}

export function assertSafeLocalMutationUrl(value, label = "API URL") {
  const target = classifyMutationTarget(value);
  if (target.isKnownProduction) {
    throw new Error(`Refusing to run mutating smoke against known production ${label}: ${target.origin}`);
  }
  if (!target.isLocal) {
    throw new Error(
      `Refusing to run mutating smoke against non-local ${label}: ${target.origin}. ` +
      "Production smokes must be read-only; staging mutation smokes need an explicit test-store policy.",
    );
  }
}

