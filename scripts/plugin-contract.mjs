#!/usr/bin/env node
// The SDK's copy of the stable app API contract
// (apps/api/src/openapi/stable-operations.snapshot.json), which
// `createContractApi` in `@scalius/plugin-sdk/testing` checks `ctx.api.call`
// against. The SDK cannot import the API app, and a published SDK has no API
// app at all, so it carries the sealed snapshot as a generated module.
// `packages/plugin-sdk/src/testing-contract.test.ts` fails when the copy is
// stale; refresh it with:
//
//   node scripts/plugin-contract.mjs

import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";

const root = resolve(import.meta.dirname, "..");
export const STABLE_SNAPSHOT = join(root, "apps/api/src/openapi/stable-operations.snapshot.json");
export const SDK_CONTRACT_GEN = join(root, "packages/plugin-sdk/src/testing-contract.gen.ts");
/** Every operation the host knows, with its stability (generated from the OpenAPI contract). */
export const AGENT_OPERATIONS_MANIFEST = join(root, "apps/api/src/generated/agent-operations.gen.txt");

/** The ids of operations that exist but are not stable: the host refuses an app's call to one with 403 `api_operation_not_stable`. */
export function nonStableOperationIds(manifestText) {
  const { operations } = JSON.parse(manifestText);
  return [...new Set(operations.filter((operation) => operation.stability !== "stable").map((operation) => operation.operationId))].sort();
}

/** The generated module: the snapshot as one JSON string, so the type checker reads a string, not a 400 KB literal. */
export function renderContractModule(snapshotText, manifestText) {
  const compact = JSON.stringify(JSON.parse(snapshotText));
  return [
    "// Generated by `node scripts/plugin-contract.mjs` from",
    "// apps/api/src/openapi/stable-operations.snapshot.json and",
    "// apps/api/src/generated/agent-operations.gen.txt. Do not edit by hand.",
    "/* eslint-disable */",
    'import type { StableContract } from "./testing-contract";',
    "",
    `export const STABLE_CONTRACT: StableContract = JSON.parse(${JSON.stringify(compact)});`,
    "",
    "/** Operations that exist but are not stable (beta or internal): an app's call is refused with 403 `api_operation_not_stable`. */",
    `export const NON_STABLE_OPERATION_IDS: readonly string[] = JSON.parse(${JSON.stringify(JSON.stringify(nonStableOperationIds(manifestText)))});`,
    "",
  ].join("\n");
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  writeFileSync(SDK_CONTRACT_GEN, renderContractModule(readFileSync(STABLE_SNAPSHOT, "utf8"), readFileSync(AGENT_OPERATIONS_MANIFEST, "utf8")));
  console.log("Updated packages/plugin-sdk/src/testing-contract.gen.ts");
}
