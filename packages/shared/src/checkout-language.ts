const CHECKOUT_LANGUAGE_PRESETS: Record<string, CheckoutLanguageData> = {
  en: { ...ENGLISH_CHECKOUT_LANGUAGE_DATA },
  bn: BANGLA_CHECKOUT_LANGUAGE_DATA,
};

function parseStoredLanguageData(value: unknown): Record<string, unknown> {
  if (value && typeof value === "object" && !Array.isArray(value)) {
    return value as Record<string, unknown>;
  }
  if (typeof value !== "string") return {};
  try {
    const parsed = JSON.parse(value) as unknown;
    return parsed && typeof parsed === "object" && !Array.isArray(parsed)
      ? (parsed as Record<string, unknown>)
      : {};
  } catch {
    return {};
  }
}

export function checkoutLanguageBaseCode(code: unknown): string {
  if (typeof code !== "string") return "en";
  return code.trim().toLowerCase().split(/[-_]/, 1)[0] || "en";
}

export function getCheckoutLanguagePreset(code: unknown): CheckoutLanguageData {
  const preset = CHECKOUT_LANGUAGE_PRESETS[checkoutLanguageBaseCode(code)];
  return { ...(preset ?? ENGLISH_CHECKOUT_LANGUAGE_DATA) };
}

function comparableDefaultText(value: string): string {
  return value
    .trim()
    .toLocaleLowerCase("en")
    .replaceAll("…", "...")
    .replace(/[.!]+$/u, "")
    .replace(/\s+/g, " ");
}

/**
 * Stored values are merchant overrides. Older records persisted the English
 * defaults even for non-English locale codes, so an unchanged English value
 * must not shadow a built-in locale preset. Genuine custom values are kept.
 */
export function resolveCheckoutLanguageData(
  code: unknown,
  storedValue: unknown,
): CheckoutLanguageData {
  const baseCode = checkoutLanguageBaseCode(code);
  const resolved = getCheckoutLanguagePreset(baseCode);
  const stored = parseStoredLanguageData(storedValue);

  for (const key of CHECKOUT_LANGUAGE_KEYS) {
    const value = stored[key];
    if (typeof value !== "string" || value.trim() === "") continue;
    if (
      baseCode !== "en" &&
      comparableDefaultText(value) ===
        comparableDefaultText(ENGLISH_CHECKOUT_LANGUAGE_DATA[key])
    ) {
      continue;
    }
    resolved[key] = value;
  }

  return resolved;
}

export function formatCheckoutLanguageText(
  template: string,
  values: Readonly<Record<string, string | number>>,
): string {
  return template.replace(/\{([a-zA-Z][a-zA-Z0-9]*)\}/g, (match, key: string) =>
    Object.prototype.hasOwnProperty.call(values, key) ? String(values[key]) : match,
  );
}
