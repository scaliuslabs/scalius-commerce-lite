// Migration 0174 (catalogue scale): Drizzle's DDL (the per-scope facet count
// table, the buyer-state price indexes of large scopes, the price-list amount
// index), then the scope counts' backfill and the triggers that keep them
// (scripts/facet-scope-counts.ts). Both provider files and the schema
// contract entry are generated here; `__tests__/catalog-scale-migration.test.ts`
// fails when the checked-in files differ.
//
//   pnpm --filter @scalius/database exec tsx scripts/catalog-scale-migration.ts --write
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { collatePostgresTextColumns, compileSqliteDdlForPostgres, compileSqliteTriggerForPostgres } from "./postgres-schema";
import { facetScopeCountsBackfill, generateFacetScopeCountsTriggers } from "./facet-scope-counts";

export const CATALOG_SCALE_MIGRATION = { version: 174, name: "0174_catalog_scale" } as const;
const BREAKPOINT = "--> statement-breakpoint";
const HEADER = `-- Catalogue scale (docs/SCALE.md): exact facet counts per category and brand
-- (product_facet_scope_counts, kept by the triggers below), the buyer-state
-- price indexes a large category or brand reads its price range and price
-- order through, and the price-list amount index a market's price order walks.
-- Generated by packages/database/scripts/catalog-scale-migration.ts.`;

/** The CREATE TABLE / CREATE INDEX statements of a migration file. */
export function migrationDdl(source: string): string[] {
  return source.split(BREAKPOINT).map((statement) => statement.trim().replace(/^(--[^\n]*\n)+/, ""))
    .filter((statement) => /^CREATE (?:TABLE|INDEX) /i.test(statement))
    .map((statement) => statement.replace(/;$/, ""));
}

export function renderCatalogScaleMigration(ddl: readonly string[]) {
  const triggers = generateFacetScopeCountsTriggers();
  const body = [
    ...ddl.map((statement, index) => `${index === 0 ? `${HEADER}\n` : ""}${statement};`),
    facetScopeCountsBackfill,
    ...triggers.map((trigger) => `${trigger.sqlite};`),
  ];
  const digest = createHash("sha256").update(`${body.join(`\n${BREAKPOINT}\n`)}\n`).digest("hex");
  const { version, name } = CATALOG_SCALE_MIGRATION;
  const ledger = `INSERT INTO scalius_schema_migrations (version, name, source_sha256) VALUES (${version}, '${name}', '${digest}');`;
  const postgres = [
    ...ddl.map((statement, index) => `${index === 0 ? `${HEADER}\n` : ""}${collatePostgresTextColumns(compileSqliteDdlForPostgres(statement))};`),
    compileSqliteDdlForPostgres(facetScopeCountsBackfill),
    ...triggers.map((trigger) => compileSqliteTriggerForPostgres({ name: trigger.name, sql: trigger.sqlite })),
    ledger,
  ];
  return {
    digest,
    sqlite: [...body, ledger].join(`\n${BREAKPOINT}\n`) + "\n",
    postgres: postgres.join(`\n${BREAKPOINT}\n`) + "\n",
  };
}

export const CATALOG_SCALE_MIGRATION_PATHS = {
  sqlite: fileURLToPath(new URL(`../migrations/${CATALOG_SCALE_MIGRATION.name}.sql`, import.meta.url)),
  postgres: fileURLToPath(new URL(`../migrations/postgres/${CATALOG_SCALE_MIGRATION.name}.sql`, import.meta.url)),
};

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1] && process.argv.includes("--write")) {
  const rendered = renderCatalogScaleMigration(migrationDdl(readFileSync(CATALOG_SCALE_MIGRATION_PATHS.sqlite, "utf8")));
  writeFileSync(CATALOG_SCALE_MIGRATION_PATHS.sqlite, rendered.sqlite);
  writeFileSync(CATALOG_SCALE_MIGRATION_PATHS.postgres, rendered.postgres);
  const contractPath = new URL("../src/schema-contract.ts", import.meta.url);
  const { version, name } = CATALOG_SCALE_MIGRATION;
  let contract = readFileSync(contractPath, "utf8")
    .replace(/export const CURRENT_DATABASE_SCHEMA = \{\n {2}version: \d+,\n {2}name: "[^"]+",/, `export const CURRENT_DATABASE_SCHEMA = {\n  version: ${version},\n  name: "${name}",`);
  const entry = `  {\n    version: ${version},\n    name: "${name}",\n    sourceSha256: "${rendered.digest}",\n  },\n`;
  contract = contract.includes(`    version: ${version},\n    name: "${name}",`)
    ? contract.replace(new RegExp(` {2}\\{\\n {4}version: ${version},[\\s\\S]*?\\n {2}\\},\\n`), entry)
    : contract.replace("] as const;", `${entry}] as const;`);
  writeFileSync(contractPath, contract);
  process.stdout.write(`Generated ${name}: digest ${rendered.digest}\n`);
}
