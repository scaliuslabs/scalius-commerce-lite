-- Markets step 3b follow-up: the checkout config reads the set of countries
-- the active markets sell to (its accepted phone countries), not the markets'
-- names or presences. The key mk:selling advances only when a country of an
-- active market is added, removed or moved, or a market's status changes
-- (generated from packages/shared/src/cache-deps.ts); a rename of a market
-- leaves it, and every other market's checkout config, valid. Triggers only.
CREATE TRIGGER `cdep_markets_selling_upd` AFTER UPDATE ON `markets`
WHEN (OLD.`status` IS NOT NEW.`status`)
BEGIN
  INSERT INTO `cache_dep` (`dep`, `seq`)
  SELECT key_rows.dep, COALESCE((SELECT `seq` FROM `cache_clock` WHERE `id` = 1), 0) + 1 FROM (SELECT key_list.value AS dep FROM json_each(json_array('mk:selling', 't:markets')) AS key_list) AS key_rows
  WHERE key_rows.dep IS NOT NULL AND COALESCE((SELECT `coarse` FROM `cache_clock` WHERE `id` = 1), 0) = 0
  UNION ALL SELECT 'store', COALESCE((SELECT `seq` FROM `cache_clock` WHERE `id` = 1), 0) + 1 WHERE COALESCE((SELECT `coarse` FROM `cache_clock` WHERE `id` = 1), 0) = 1
  ON CONFLICT (`dep`) DO UPDATE SET `seq` = excluded.`seq`;
END;
