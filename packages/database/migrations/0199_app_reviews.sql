-- App reviews: an app (an import of history, a reviews app) writes reviews
-- through the stable app API. A buyer's review stays a verified purchase of
-- one delivered order line; an app's review names the app (`app_id`,
-- `author_type = 'app'`) and may name no line, so `order_id` and
-- `order_item_id` become nullable: only a review on a line is verified, and
-- the line trigger still refuses any named line that was not handed over on
-- a delivered order. SQLite cannot drop NOT NULL in place, so the table is
-- rebuilt: every row keeps its rowid (the FTS5 index points at it), and every
-- trigger is reinstalled (the cache dependency ones as generated by
-- scripts/cache-dep-triggers.ts; `app_id` is noise there). The stable list
-- walks (updated_at, id).
