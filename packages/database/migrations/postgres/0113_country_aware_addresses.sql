-- Markets step 3a (docs/MARKETS-DESIGN.md D7): country-aware addresses.
-- Orders gain the canonical shipping-address snapshot (country, second line,
-- dependent locality, locality, admin area, postal code, company, recipient
-- name and phone when not the contact, validation_skipped) beside
-- Bangladesh's City/Thana/Area adapter; shipping_address stays the first
-- line. Every existing shipped order is a Bangladesh address: the backfill
-- sets BD and copies the city and thana names into locality and dependent
-- locality (no admin area: a delivery location knows no division). The
-- shipping-address triggers become per country (generated by
-- packages/database/scripts/shipping-address-triggers.ts). Customers get an
-- address book (customer_addresses, one default per customer); each
-- embedded customer address moves into it as the default, and the old
-- columns leave customers and customer_history. A guest record's first
-- shipping order seeds its default address (trigger
-- orders_seed_customer_address). The event triggers of orders and customers
-- are re-created with the new column lists, and address-book writes are
-- customer.updated (packages/database/scripts/event-outbox-triggers.ts).
-- The address book is private: no cache dependency.
