CREATE OR REPLACE FUNCTION scalius_compat."orders_shipping_address_required_insert_fn"()
RETURNS trigger
LANGUAGE plpgsql
AS $trigger_function$
BEGIN
  IF NOT coalesce((NEW."requires_shipping" = 1
  AND (
    NEW."shipping_address" IS NULL OR trim(NEW."shipping_address") = ''
    OR (coalesce(NEW."shipping_country_code", 'BD') = 'BD' AND (NEW."city" IS NULL OR NEW."zone" IS NULL))
    OR (NEW."shipping_country_code" <> 'BD' AND NEW."shipping_validation_skipped" = 0 AND (
      (position('|' || NEW."shipping_country_code" || '|' in '|AE|AG|CO|GI|HK|ID|JP|KY|MO|NR|SG|SM|VG|VN|') = 0 AND coalesce(trim(NEW."shipping_locality"), '') = '')
      OR (position('|' || NEW."shipping_country_code" || '|' in '|AE|AS|AU|BR|CA|CN|CO|CR|ES|FM|HK|HN|ID|IN|IQ|IT|JM|JP|KN|KR|KY|MH|MP|MX|NR|PF|PG|PW|RU|SO|SV|TW|UM|US|VE|VI|VN|') > 0 AND coalesce(trim(NEW."shipping_admin_area"), '') = '')
      OR (position('|' || NEW."shipping_country_code" || '|' in '|AS|AT|AU|AX|BE|BL|BR|CA|CH|CN|CZ|DE|DK|EE|ES|FI|FK|FM|FR|GB|GF|GG|GL|GP|GR|GS|GU|HU|IM|IN|IO|IT|JE|JP|KR|LI|LT|LU|LV|MF|MH|MP|MQ|MX|MY|NC|NL|NO|NZ|PF|PL|PM|PN|PR|PT|PW|RE|RO|RU|SE|SG|SH|SJ|SK|SM|TC|TR|TW|UA|US|VI|WF|YT|ZA|') > 0 AND coalesce(trim(NEW."shipping_postal_code"), '') = '')
