// How the storefront runs an app's storefront module (docs/STOREFRONT-COMPONENTS.md):
//
// - bundled apps (every plan): the module `pnpm plugin` compiled into this
//   Worker (extensions/bundled.gen.ts), called in process with a structured
//   clone of the batch. The input shape matches the isolate protocol,
//   but bundled code is trusted host code, not isolated execution;
// - uploaded and registry apps (Workers Paid, `LOADER`): the module runs in
//   its own Dynamic Worker, kept warm by `<plugin id>:<release>`, with no
//   bindings and no network. Its code is read once per isolate from the API,
//   verified against the release's sealed digest there, and kept in the Cache API.
//
// Either way the module gets the same batch and answers the same reply.

import {
  STOREFRONT_COMPONENT_ABI,
  STOREFRONT_COMPONENT_LIMITS,
  STOREFRONT_MODULE_FILE,
  storefrontIsolateId,
  type StorefrontExtension,
  type StorefrontModule,
  type StorefrontRenderBatch,
  type StorefrontRenderReply,
} from "@scalius/shared/plugins/storefront-components";
import { BUNDLED_STOREFRONT_EXTENSIONS } from "@/extensions/bundled.gen";
import { readExtensionFile } from "./files";

/** One bundled app's compiled storefront part (generated by `pnpm plugin`). */
export interface BundledStorefrontExtension {
  /** The release it was compiled from (the lockfile's bundle SHA-256). */
  release: string;
  module: () => Promise<{ default: StorefrontModule }>;
  files: () => Promise<{ FILES: Readonly<Record<string, { type: string; text?: string; base64?: string }>> }>;
}

/** The isolates' compatibility date: the platform moves it, apps do not choose it. */
export const STOREFRONT_ISOLATE_COMPATIBILITY_DATE = "2026-07-30";

/** The main module of every storefront isolate: the RPC entry around the app's module. */
export const STOREFRONT_ISOLATE_MAIN = [
  'import { WorkerEntrypoint } from "cloudflare:workers";',
  'import storefront from "./storefront.js";',
  "export default class StorefrontIsolate extends WorkerEntrypoint {",
  "  render(batch) { return storefront.render(batch); }",
  "}",
  "",
].join("\n");

/** The part of a Worker Loader binding the storefront uses. */
export interface StorefrontWorkerLoader {
  get(id: string, code: () => Promise<{
    compatibilityDate: string;
    mainModule: string;
    modules: Record<string, string>;
    env: Record<string, never>;
    globalOutbound: null;
    limits?: { cpuMs?: number };
  }>): { getEntrypoint(): unknown };
}

export interface ExtensionRuntime {
  env: { LOADER?: StorefrontWorkerLoader; BACKEND_API?: Fetcher };
}

export class ExtensionUnavailableError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "ExtensionUnavailableError";
  }
}

function isReply(value: unknown): value is StorefrontRenderReply {
  return typeof value === "object" && value !== null
    && (value as { abi?: unknown }).abi === STOREFRONT_COMPONENT_ABI
    && Array.isArray((value as { results?: unknown }).results);
}

/** Answers one batch with the app's module, wherever it runs. */
export async function runStorefrontModule(
  runtime: ExtensionRuntime,
  extension: StorefrontExtension,
  batch: StorefrontRenderBatch,
): Promise<StorefrontRenderReply> {
  if (extension.source === "bundled") {
    const bundled = BUNDLED_STOREFRONT_EXTENSIONS[extension.pluginId];
    // The installation runs another release than this Worker was built with: draw nothing until a deploy.
    if (!bundled || bundled.release !== extension.release) {
      throw new ExtensionUnavailableError(`${extension.pluginId} ${extension.release.slice(0, 12)} is not the release compiled into this storefront.`);
    }
    const module = (await bundled.module()).default;
    const reply = module.render(structuredClone(batch));
    if (!isReply(reply)) throw new Error(`${extension.pluginId} answered no render reply.`);
    return structuredClone(reply);
  }
  const loader = runtime.env.LOADER;
  if (!loader) throw new ExtensionUnavailableError(`${extension.pluginId} needs the storefront's Worker Loader (Workers Paid).`);
  const isolate = loader.get(storefrontIsolateId(extension.pluginId, extension.release), async () => {
    const file = await readExtensionFile(runtime.env, extension.pluginId, extension.release, STOREFRONT_MODULE_FILE);
    if (!file) throw new ExtensionUnavailableError(`${extension.pluginId}: its storefront module could not be read.`);
    return {
      compatibilityDate: STOREFRONT_ISOLATE_COMPATIBILITY_DATE,
      mainModule: "main.js",
      modules: { "main.js": STOREFRONT_ISOLATE_MAIN, "storefront.js": new TextDecoder().decode(file.bytes) },
      env: {},
      globalOutbound: null,
      limits: { cpuMs: STOREFRONT_COMPONENT_LIMITS.renderCpuMs },
    };
  });
  const entrypoint = isolate.getEntrypoint() as { render(batch: StorefrontRenderBatch): Promise<unknown> };
  const reply = await entrypoint.render(batch);
  if (!isReply(reply)) throw new Error(`${extension.pluginId} answered no render reply.`);
  return reply;
}
