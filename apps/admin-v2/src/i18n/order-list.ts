export type OrderListMessageKey = keyof typeof orderListMessages.en;

type Translate = (key: OrderListMessageKey, vars?: Record<string, string | number>) => string;

type PluralBase<K> = K extends `${infer Base}.one` ? Base : never;

/** `<base>.one` for exactly one, otherwise `<base>.other`. */
export function pluralKey(base: PluralBase<OrderListMessageKey>, count: number): OrderListMessageKey {
  return `${base}.${count === 1 ? "one" : "other"}` as OrderListMessageKey;
}

export function itemCountLabel(t: Translate, count: number): string {
  return count === 1 ? t("itemsOne") : t("itemsOther", { count });
}

/** Courier delivery status label, falling back to the raw status for new courier states. */
export function shipmentStatusLabel(t: Translate, status: string): string {
  const key = `shipment.${status.toLowerCase()}`;
  return key in orderListMessages.en ? t(key as OrderListMessageKey) : status.replace(/_/g, " ");
}
