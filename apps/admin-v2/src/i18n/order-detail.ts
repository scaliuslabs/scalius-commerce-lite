export type OrderDetailMessageKey = keyof typeof orderDetailMessages.en;

type Translate = (key: OrderDetailMessageKey, vars?: Record<string, string | number>) => string;

/** Catalog label for `${prefix}${value}`, or the raw value made readable. */
export function orderDetailLabel(t: Translate, prefix: string, value: string): string {
  const key = `${prefix}${value.toLowerCase()}`;
  if (key in orderDetailMessages.en) return t(key as OrderDetailMessageKey);
  const text = value.replace(/[_-]+/g, " ").trim();
  return text.charAt(0).toUpperCase() + text.slice(1);
}
